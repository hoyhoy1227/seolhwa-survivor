import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, '..');
const spriteDirectory = path.join(projectRoot, 'assets', 'sprites');
const outputPath = path.join(projectRoot, 'src', 'sprite-data.js');

const spriteFiles = [
  'dokkaebi.png',
  'gumiho.png',
  'haechi.png',
  'sansin.png',
  'cheoyong.png',
  'baridegi.png',
  'sejong.png',
  'lantern.png',
  'treasure-chest.png',
  'enemy-dokkaebi.png',
  'enemy-gaksi.png',
  'enemy-jeoseung.png',
  'boss-dokkaebi.png',
  'boss-gumiho.png',
  'boss-bulgasari.png',
  'boss-sangun.png',
  'boss-yeoksin.png',
  'boss-yeomra.png',
  'device-brazier.png',
  'device-mist-stone.png',
  'device-golden-seal.png',
  'device-wind-totem.png',
  'device-moon-drum.png',
  'device-soul-well.png',
  'prop-market-landmark-v1.png',
  'prop-fox-shrine-v1.png',
  'prop-golden-gate-v1.png',
  'prop-mountain-shrine-v1.png',
  'prop-moon-court-v1.png',
  'prop-underworld-memorial-v1.png',
  'ground-forest-v2.png'
];

const spriteData = Object.fromEntries(spriteFiles.map(fileName => {
  const filePath = path.join(spriteDirectory, fileName);
  const encoded = fs.readFileSync(filePath).toString('base64');
  return [fileName, `data:image/png;base64,${encoded}`];
}));

const output = [
  '// Generated by scripts/build-sprite-data.mjs. Do not edit by hand.',
  `window.EMBEDDED_SPRITES = Object.freeze(${JSON.stringify(spriteData)});`,
  ''
].join('\n');

fs.writeFileSync(outputPath, output, 'utf8');
console.log(`Embedded ${spriteFiles.length} sprites in ${path.relative(projectRoot, outputPath)}.`);
